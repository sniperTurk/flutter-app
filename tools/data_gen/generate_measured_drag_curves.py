#!/usr/bin/env python3
"""Generates lib/data/measured_drag_curves.dart from data/drag-curves/measured/*.json.

Measured (Doppler radar / spark range) Cd-vs-Mach curves of specific bullets
(owner, 2026-10-11). A record reaches the app only when it
- is flagged "use_in_app": true,
- carries a permitted license and an https source URL,
- has 5..500 strictly rising Mach points with 0 < Cd <= 2,
- covers subsonic to supersonic flight (first Mach <= 0.8, last Mach >= 2.0):
  the solver holds Cd constant outside the curve, so a gap would bias the
  long-range drop,
- names a bullet of lib/data/bullet_library.dart exactly (brand, name, grain).
Every other record is listed on stderr with its reason. Nothing is guessed.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
DATA = REPO / 'data' / 'drag-curves' / 'measured'
LIBRARY = REPO / 'lib' / 'data' / 'bullet_library.dart'
OUT = REPO / 'lib' / 'data' / 'measured_drag_curves.dart'

LICENSES = ('us-government-public-release', 'cc-by-4.0', 'cc0-1.0', 'written-permission')
MIN_POINTS, MAX_POINTS = 5, 500
MAX_FIRST_MACH, MIN_LAST_MACH = 0.8, 2.0

_STR = r"'((?:[^'\\]|\\.)*)'"
_ENTRY = re.compile(r"LibraryBullet\(" + _STR + r",\s*" + _STR + r",\s*" + _STR +
                    r",\s*[-\d.]+,\s*[-\d.]+,\s*([\d.]+),")


def _unescape(s: str) -> str:
    return re.sub(r'\\(.)', r'\1', s)


def parse_library(text: str) -> set[tuple[str, str, float]]:
    """(brand, name, grain) of every LibraryBullet in the Dart source."""
    return {(_unescape(m.group(1)), _unescape(m.group(2)), float(m.group(4)))
            for m in _ENTRY.finditer(text)}


def _points_ok(points) -> bool:
    if not isinstance(points, list) or not MIN_POINTS <= len(points) <= MAX_POINTS:
        return False
    last = -1.0
    for p in points:
        if not isinstance(p, list) or len(p) != 2:
            return False
        m, cd = p
        if not all(isinstance(v, (int, float)) and math.isfinite(v) for v in (m, cd)):
            return False
        if m <= last or m > 10 or not 0 < cd <= 2:
            return False
        last = m
    return points[0][0] >= 0


def reject_reason(r: dict, library: set[tuple[str, str, float]]) -> str | None:
    """None when the record may reach the app, else the reason (Turkish)."""
    if r.get('use_in_app') is not True:
        return 'use_in_app false: ' + str(r.get('use_in_app_reason') or '')
    if r.get('license') not in LICENSES or not str(r.get('license_note') or '').strip():
        return f"izinli lisans yok ({r.get('license')!r})"
    if not str(r.get('source_url') or '').startswith('https://'):
        return 'kaynak bağlantısı https değil'
    points = r.get('points')
    if not _points_ok(points):
        return 'nokta listesi geçersiz'
    if points[0][0] > MAX_FIRST_MACH or points[-1][0] < MIN_LAST_MACH:
        return (f'Mach kapsamı yetersiz ({points[0][0]}–{points[-1][0]}; '
                f'gerekli ≤{MAX_FIRST_MACH} ve ≥{MIN_LAST_MACH})')
    lib = r.get('library')
    if not isinstance(lib, dict):
        return 'kütüphane eşleşmesi yok'
    for brand, name, grain in library:
        if (brand == lib.get('brand') and name == lib.get('name')
                and isinstance(lib.get('grain'), (int, float))
                and abs(grain - lib['grain']) < 0.01):
            return None
    return 'kütüphanede birebir aynı mermi yok'


def _dart_str(s: str) -> str:
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$') + "'"


def _num(v) -> str:
    v = float(v)
    return repr(v)


def render(records: list[dict]) -> str:
    out = [
        '// dart format off\n',
        '// GENERATED by tools/data_gen/generate_measured_drag_curves.py from\n',
        '// data/drag-curves/measured/*.json. Do not edit by hand.\n',
        "import 'measured_drag_lookup.dart';\n\n",
        '/// Measured Cd-vs-Mach curves linked to bullet-library entries.\n',
        'const measuredDragCurves = <MeasuredDragCurve>[\n',
    ]
    for r in records:
        lib = r['library']
        pts = ', '.join(f'[{_num(m)}, {_num(cd)}]' for m, cd in r['points'])
        out.append(
            f"  MeasuredDragCurve(id: {_dart_str(r['id'])}, "
            f"brand: {_dart_str(lib['brand'])}, name: {_dart_str(lib['name'])}, "
            f"grain: {_num(lib['grain'])}, method: {_dart_str(r['method'])}, "
            f"sourceUrl: {_dart_str(r['source_url'])}, "
            f"license: {_dart_str(r['license'])}, points: [{pts}]),\n")
    out.append('];\n')
    return ''.join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--data', type=Path, default=DATA)
    ap.add_argument('--library', type=Path, default=LIBRARY)
    ap.add_argument('--out', type=Path, default=OUT)
    a = ap.parse_args(argv)
    library = parse_library(a.library.read_text())
    accepted = []
    for f in sorted(a.data.glob('*.json')):
        r = json.loads(f.read_text())
        why = reject_reason(r, library)
        if why is None:
            accepted.append(r)
        else:
            print(f'skip {f.name}: {why}', file=sys.stderr)
    a.out.write_text(render(accepted))
    print(f'measured curves: {len(accepted)} written to {a.out.name}', file=sys.stderr)
    return 0


if __name__ == '__main__':
    sys.exit(main())
